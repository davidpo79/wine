-- UGC creator contracts with an online electronic signature (David, 21/11/2026).
CREATE TABLE IF NOT EXISTS "creator_contracts" (
	"id" serial PRIMARY KEY NOT NULL,
	"token" text NOT NULL,
	"application_id" integer,
	"creator_name" text NOT NULL,
	"email" text NOT NULL,
	"phone" text,
	"id_number" text,
	"address" text,
	"city" text,
	"iban" text,
	"videos" integer NOT NULL,
	"seconds" integer NOT NULL,
	"fee_cents" integer NOT NULL,
	"delivery_date" text NOT NULL,
	"company_signer" text NOT NULL,
	"status" text DEFAULT 'sent' NOT NULL,
	"otp_hash" text,
	"otp_expires_at" timestamp with time zone,
	"otp_attempts" integer DEFAULT 0 NOT NULL,
	"otp_sent_at" timestamp with time zone,
	"sent_at" timestamp with time zone,
	"sent_via" text,
	"signed_at" timestamp with time zone,
	"signer_ip" text,
	"signer_ua" text,
	"doc_hash" text,
	"signature_png" text,
	"signed_pdf" text,
	"created_at" timestamp with time zone DEFAULT now() NOT NULL,
	CONSTRAINT "creator_contracts_token_unique" UNIQUE("token")
);
